import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import documents from '../../backend/utils/crawlDocuments.js';
const publicRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../public');
fs.mkdirSync(publicRoot,{recursive:true});
fs.writeFileSync(path.join(publicRoot,'sitemap.xml'),documents.sitemap([]));
fs.writeFileSync(path.join(publicRoot,'robots.txt'),documents.robots);
fs.writeFileSync(path.join(publicRoot,'llms.txt'),documents.llms([]));
console.log('Static crawl documents generated; production rewrites serve current published database content.');
